const bullets = (items, empty) => {
  if (items.length === 0) return [`- ${empty}`];
  return items.map((item) => `- ${item}`);
};

const constraintSentence = (label, value) => {
  if (value === "forbidden") return `${label} is forbidden by the plain text.`;
  if (value === "allowed")
    return `The plain text allows ${label}. This generator still did not use it.`;
  return `The plain text does not say whether ${label} is allowed. Leave it out.`;
};

const declared = (value) => value ?? "not specified";

/** Render a plan that records what was extracted and what was not run. */
export const renderPlan = (spec) => {
  const lines = [
    `# Build plan: ${spec.name}`,
    "",
    "Generated by `build-from-text` from local plain text.",
    "This plan has not been executed.",
    "The acceptance tests listed below have not been run.",
    "This generator did not contact a network, did not emit telemetry, and did not compile a binary.",
    "Upstream SECURITY.md and DISCLAIMER.md still apply to work derived from this plan.",
    "",
    "## Declared spec",
    "",
    `- Kind: ${spec.kind}`,
    `- Language: ${declared(spec.language)}`,
    `- Entry: ${declared(spec.entry)}`,
    `- Summary: ${spec.summary === "" ? "not specified" : spec.summary}`,
    "",
    "The entry path was copied from the text. This generator did not check that it exists.",
    "",
    "## Constraints",
    "",
    `- network: ${spec.constraints.network}`,
    `- telemetry: ${spec.constraints.telemetry}`,
    ...bullets(spec.constraints.notes, "No extra constraint notes."),
    "",
    constraintSentence("Network", spec.constraints.network),
    constraintSentence("Telemetry", spec.constraints.telemetry),
    "",
    "## Behaviors",
    "",
    ...bullets(spec.behaviors, "No behaviors were declared."),
    "",
    "## Acceptance tests",
    "",
    ...bullets(spec.acceptanceTests, "No acceptance tests were declared."),
    "",
    "## Steps",
    "",
    "1. Treat `spec.schema.json` as the extracted contract. Its `$schema` value is a dialect identifier and was not downloaded.",
    "2. Implement only the declared behaviors.",
    "3. Start from `skeleton.test.ts`. Each `it.todo` is a placeholder. This generator did not run that file.",
    "4. Do not add network access or telemetry unless that constraint is `allowed`.",
    "",
  ];
  if (spec.notes.length > 0)
    lines.push("## Notes", "", ...bullets(spec.notes, ""), "");
  return `${lines.join("\n")}`;
};
